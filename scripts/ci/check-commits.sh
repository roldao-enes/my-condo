#!/usr/bin/env bash
# Enforces Conventional Commits (https://www.conventionalcommits.org).
#
#   check-commits.sh --message-file FILE   one message (used by .githooks/commit-msg)
#   check-commits.sh BASE..HEAD            every non-merge commit in a range (used by CI)
#
# Format of the first line:  type(optional-scope)!: description
# `fix` releases a PATCH, `feat` a MINOR, and `!` or a `BREAKING CHANGE:` footer a MAJOR
# (see docs/contributing.md and scripts/release/next-version.sh).
set -euo pipefail

types='feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert'
pattern="^(${types})(\\([a-z0-9._/-]+\\))?!?: [^ ].*"

# Returns 0 if the message (arg 1) is acceptable; prints the reason and returns 1 otherwise.
check_message() {
  local subject
  subject="$(printf '%s\n' "$1" | head -n1)"
  # Generated by git itself: merges, reverts, fixup!/squash! (those are squashed before merging).
  case "$subject" in
    "Merge "* | "Revert \""* | "fixup! "* | "squash! "* | "amend! "*) return 0 ;;
  esac
  if [[ "$subject" =~ $pattern ]]; then return 0; fi
  echo "  not a conventional commit: $subject" >&2
  return 1
}

fail_help() {
  cat >&2 <<HELP

Commit messages must follow Conventional Commits:  <type>(<scope>)<!>: <description>
  types: ${types//|/, }
  examples:  fix: keep the invoice total when a fraction is removed
             feat(audit): export the log as CSV
             feat!: drop support for the v1 backup format
Only fix (PATCH), feat (MINOR) and breaking changes (MAJOR) trigger a release.
HELP
}

if [[ "${1:-}" == "--message-file" ]]; then
  # Ignore git's comment lines (lines starting with #) in the editor template.
  msg="$(grep -v '^#' "${2:?message file required}" || true)"
  check_message "$msg" || { fail_help; exit 1; }
  exit 0
fi

range="${1:?usage: check-commits.sh --message-file FILE | BASE..HEAD}"
bad=0
while read -r sha; do
  [[ -z "$sha" ]] && continue
  if ! check_message "$(git log -1 --format=%B "$sha")"; then
    echo "    in commit ${sha:0:10}" >&2
    bad=1
  fi
done < <(git rev-list --no-merges "$range")
if [[ $bad -ne 0 ]]; then fail_help; exit 1; fi
echo "All commits in $range follow Conventional Commits."
